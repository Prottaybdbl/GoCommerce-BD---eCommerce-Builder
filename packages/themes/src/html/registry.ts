/**
 * Gallery tab for a template. Derived from the source folder when the template
 * has one; the section-engine archetypes sit with the single landing pages and
 * anything shop-tier is e-commerce.
 */
export function getTemplateCategory(templateId: string): TemplateCategory {
  const info = TEMPLATE_REGISTRY[templateId];
  if (!info) return "single-landing";
  if (info.categoryDir?.startsWith("1.")) return "single-landing";
  if (info.categoryDir?.startsWith("2.")) return "multi-landing";
  if (info.categoryDir?.startsWith("3.") || info.tier === "shop") return "ecommerce";
  return "single-landing";
}
